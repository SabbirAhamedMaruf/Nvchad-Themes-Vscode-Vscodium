export const FLAT_GROUPS = { SURFACES, POPUPS, FIELDS, FRAMES, CLEAR, BORDERED }

export function bordered({ fg }) {
  return Object.fromEntries(BORDERED.map((key) => [key, fg('WinSeparator')]))
}

export function flat({ c, fg, bg, type }) {
  const surface = bg('Normal')
  // eldritch paints its float with the editor color, which would make a frameless popup vanish
  const popup = bg('NormalFloat') === surface ? c.darker_black : bg('NormalFloat')
  const field = bg('TelescopePromptNormal')
  const hover = c.black2
  const selected = c.one_bg2
  // base46 lightens the statusline text, which on a light surface leaves it close to invisible
  const statusText = type === 'light' ? fg('TbBufOff') : fg('St_gitIcons')

  const out = {}
  for (const key of SURFACES) out[key] = surface
  for (const key of POPUPS) out[key] = popup
  for (const key of FIELDS) out[key] = field
  for (const key of FRAMES) out[key] = NONE
  for (const key of CLEAR) out[key] = NONE

  return {
    ...out,

    // lists sit on the editor color now, so nvim-tree's cursor line (also the editor color) cannot mark a row
    'list.hoverBackground': hover,
    'list.inactiveSelectionBackground': c.one_bg,
    'list.inactiveFocusBackground': c.one_bg,
    'list.activeSelectionBackground': selected,
    'list.focusBackground': selected,
    'list.dropBackground': selected,
    'tree.indentGuidesStroke': fg('NvimTreeIndentMarker'),
    'settings.focusedRowBackground': hover,
    'settings.rowHoverBackground': hover,
    'welcomePage.tileHoverBackground': hover,
    'chat.requestBubbleHoverBackground': hover,
    'editorStickyScrollHover.background': hover,
    'terminalStickyScrollHover.background': hover,
    'notebook.cellHoverBackground': hover,
    'notebook.focusedCellBackground': hover,
    'notebook.selectedCellBackground': hover,

    // tabs: same surface, the active one only brighter
    'tab.activeForeground': fg('TbBufOn'),
    'tab.unfocusedActiveForeground': fg('TbBufOn'),
    'tab.inactiveForeground': fg('TbBufOff'),
    'tab.unfocusedInactiveForeground': fg('TbBufOff'),
    'tab.hoverForeground': fg('TbBufOn'),
    'tab.unfocusedHoverForeground': fg('TbBufOff'),

    // activity bar and panel tabs: active is brighter text, nothing underneath
    'activityBar.foreground': c.white,
    'activityBar.inactiveForeground': c.grey_fg,
    'panelTitle.activeForeground': c.white,
    'panelTitle.inactiveForeground': c.light_grey,

    // status bar: plain text on the surface, state shown by text color only
    'statusBar.foreground': statusText,
    'statusBar.noFolderForeground': statusText,
    'statusBar.debuggingForeground': bg('St_ReplaceMode'),
    'statusBarItem.remoteForeground': bg('St_NormalMode'),
    'statusBarItem.prominentForeground': statusText,
    'statusBarItem.errorForeground': fg('DiagnosticError'),
    'statusBarItem.warningForeground': fg('DiagnosticWarn'),
    'statusBarItem.offlineForeground': fg('DiagnosticError'),
    'statusBarItem.hoverBackground': hover,
    'statusBarItem.hoverForeground': c.white,
    'statusBarItem.compactHoverBackground': hover,
    'statusBarItem.activeBackground': selected,
    'statusBarItem.remoteHoverBackground': hover,
    'statusBarItem.remoteHoverForeground': c.white,
    'statusBarItem.prominentHoverBackground': hover,
    'statusBarItem.prominentHoverForeground': c.white,
    'statusBarItem.errorHoverBackground': hover,
    'statusBarItem.errorHoverForeground': fg('DiagnosticError'),
    'statusBarItem.warningHoverBackground': hover,
    'statusBarItem.warningHoverForeground': fg('DiagnosticWarn'),
    'statusBarItem.offlineHoverBackground': hover,
    'statusBarItem.offlineHoverForeground': fg('DiagnosticError'),

    // the title bar search box is a field like any other
    'commandCenter.activeBackground': selected,
    'commandCenter.debuggingBackground': field,
  }
}

// background fallbacks for keys VS Code would otherwise paint with its own default: flat unless the key names a popup
export function flatSurfaceFallback(key, { bg }) {
  const k = key.toLowerCase()
  if (/(widget|popup|hover|menu|float|dropdown|quickinput|peek|notification|toolbar)/.test(k)) return bg('NormalFloat')
  return bg('Normal')
}

function numbered(prefix, count, value) {
  return Object.fromEntries(Array.from({ length: count }, (_, i) => [`${prefix}${i + 1}`, value]))
}

function guides(prefix, value) {
  return numbered(prefix, 6, value)
}

// NvChad's terminal palette (base46 term.lua)
function terminalAnsi(b) {
  const names = ['Black', 'Red', 'Green', 'Yellow', 'Blue', 'Magenta', 'Cyan', 'White']
  const normal = ['base01', 'base08', 'base0B', 'base0A', 'base0D', 'base0E', 'base0C', 'base05']
  const bright = ['base03', 'base08', 'base0B', 'base0A', 'base0D', 'base0E', 'base0C', 'base07']
  const out = {}
  names.forEach((name, i) => {
    out[`terminal.ansi${name}`] = b[normal[i]]
    out[`terminal.ansiBright${name}`] = b[bright[i]]
  })
  return out
}

